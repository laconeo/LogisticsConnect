export function normalizeAndValidateRut(rawRut: string): {
  valid: boolean;
  formatted: string;
} {
  const clean = rawRut.replace(/[^0-9kK]/g, '').toUpperCase();
  if (clean.length < 7) {
    return { valid: false, formatted: rawRut };
  }
  const body = clean.slice(0, -1);
  const dv = clean.slice(-1);
  const formattedBody = body.replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return {
    valid: /^\d+$/.test(body) && /^[0-9K]$/.test(dv),
    formatted: `${formattedBody}-${dv}`,
  };
}

export function validateExcelRow(row: ExcelImportRow): ExcelRowValidation {
  const errores: string[] = [];
  const advertencias: string[] = [];
  let comuna_sugerida: string | undefined;

  const exactMatch = CHILE_COMUNAS_CATALOG.find(
    (c) => c.comuna.toLowerCase() === row.comuna_raw.trim().toLowerCase()
  );

  if (!exactMatch) {
    const fuzzy = COMUNA_FUZZY_MAP[row.comuna_raw.trim().toLowerCase()];
    comuna_sugerida = fuzzy || 'Santiago';
    errores.push(
      `Comuna "${row.comuna_raw}" fuera de catálogo (Sugerencia: ${comuna_sugerida})`
    );
  }

  if (!row.rut || !row.rut.trim()) {
    errores.push('RUT obligatorio faltante');
  } else {
    const rutCheck = normalizeAndValidateRut(row.rut);
    if (!rutCheck.valid) {
      errores.push(`Formato de RUT inválido (${row.rut})`);
    } else if (row.rut !== rutCheck.formatted) {
      advertencias.push(`RUT normalizable a ${rutCheck.formatted}`);
    }
  }

  if (!row.correo || !row.correo.includes('@')) {
    errores.push(`Correo electrónico inválido (${row.correo || 'vacío'})`);
  }

  return {
    fila: row.fila,
    es_valida: errores.length === 0,
    errores,
    advertencias,
    comuna_sugerida,
    rut_normalizado: row.rut ? normalizeAndValidateRut(row.rut).formatted : undefined,
  };
}
